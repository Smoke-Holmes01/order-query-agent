"""Evaluate a planner against fixed semantic cases and a real read-only MySQL.

Both CLI modes use the production Repository. Only the model is substituted by
mock mode. Expected rows are hand-authored, never generated by query templates.
"""

from __future__ import annotations

import argparse
from collections import Counter
from datetime import UTC, datetime
from decimal import Decimal, InvalidOperation
import json
from pathlib import Path
import re
import sys
from time import perf_counter
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
MONEY_PATTERN = re.compile(r"(?:0|[1-9][0-9]*)\.[0-9]{2}\Z")


class CountingRepository:
    """Transparent query counter; every execute is delegated to real MySQL."""

    def __init__(self, repository: Any) -> None:
        self.repository = repository
        self.query_count = 0

    def execute(self, *args: Any, **kwargs: Any) -> Any:
        self.query_count += 1
        return self.repository.execute(*args, **kwargs)

    def __getattr__(self, name: str) -> Any:
        return getattr(self.repository, name)


def normalize_value(value: Any, key: str | None = None) -> Any:
    """Compare exact money and preserve types, NULLs and duplicate rows."""
    if key == "sales_amount":
        if not isinstance(value, str) or not MONEY_PATTERN.fullmatch(value):
            raise ValueError("sales_amount must be a two-decimal string")
        try:
            return Decimal(value)
        except InvalidOperation as exc:
            raise ValueError("invalid exact money") from exc
    if key in {"sales_quantity", "product_id"}:
        if type(value) is not int:
            raise ValueError(f"{key} must be an integer")
    if isinstance(value, dict):
        return tuple(sorted((field, normalize_value(item, field)) for field, item in value.items()))
    if isinstance(value, list):
        return tuple(normalize_value(item) for item in value)
    return (type(value).__name__, value)


def rows_equal(actual: Any, expected: Any, ordered: bool = True) -> bool:
    if not isinstance(actual, list) or not isinstance(expected, list):
        return False
    try:
        actual_rows = [normalize_value(row) for row in actual]
        expected_rows = [normalize_value(row) for row in expected]
    except (ValueError, TypeError):
        return False
    if ordered:
        return actual_rows == expected_rows
    # Sorting lists (rather than sets) retains duplicate row multiplicity.
    return sorted(actual_rows, key=repr) == sorted(expected_rows, key=repr)


def check_case(case: dict[str, Any], response: dict[str, Any], query_count: int) -> dict[str, Any]:
    """Check semantics independently of SQL text and answer wording."""
    query_case = case["expected_status"] == "success"
    status_ok = response.get("status") == case["expected_status"]
    plan_ok = response.get("plan") == case["expected_plan"]
    plan_status_ok = status_ok and plan_ok
    failures: list[str] = []
    if not status_ok:
        failures.append("STATUS_MISMATCH")
    if not plan_ok:
        failures.append("PLAN_MISMATCH")

    data = response.get("data")
    rows_ok = rows_equal(data, case["expected_rows"], case.get("ordered", True))
    if not rows_ok:
        failures.append("ROWS_MISMATCH")
    query_ok = query_count == (1 if query_case else 0)
    query_ok = query_ok and ((response.get("query") is not None) if query_case else response.get("query") is None)
    if not query_ok:
        failures.append("QUERY_EXECUTION_MISMATCH")
    if response.get("error") is not None:
        failures.append("UNEXPECTED_ERROR")

    answer = response.get("answer", "")
    answer_ok = isinstance(answer, str) and bool(answer)
    if query_case and answer_ok:
        plan = case["expected_plan"]
        answer_ok = "已支付" in answer and "模拟" in answer
        answer_ok = answer_ok and plan["start_date"] in answer and plan["end_date"] in answer
        if data:
            answer_ok = answer_ok and "人民币" in answer
            answer_ok = answer_ok and all(row["sales_amount"] in answer for row in data)
        else:
            answer_ok = answer_ok and "该区间没有符合口径的记录" in answer
    answer_ok = answer_ok and all(text in answer for text in case.get("answer_contains", []))
    if not answer_ok:
        failures.append("ANSWER_MISMATCH")

    total_ok = True
    if "expected_total_sales_amount" in case:
        try:
            total_ok = isinstance(data, list) and sum(
                (Decimal(row["sales_amount"]) for row in data), Decimal("0.00")
            ) == Decimal(case["expected_total_sales_amount"])
        except (KeyError, TypeError, InvalidOperation):
            total_ok = False
        if not total_ok:
            failures.append("TOTAL_MISMATCH")

    # An empty result counts only when its plan and interval are also correct.
    result_correct = plan_status_ok and rows_ok and query_ok and total_ok and response.get("error") is None
    return {
        "id": case["id"],
        "expected_status": case["expected_status"],
        "actual_status": response.get("status"),
        "plan_status_passed": plan_status_ok,
        "result_correct": result_correct if query_case else None,
        "answer_passed": answer_ok,
        "database_query_count": query_count,
        "passed": not failures,
        "failures": failures,
        "error_code": (response.get("error") or {}).get("code"),
        "error_category": (response.get("error") or {}).get("category"),
        "actual_plan": response.get("plan"),
        "actual_data": data,
    }


def load_cases(path: Path) -> list[dict[str, Any]]:
    cases = json.loads(path.read_text(encoding="utf-8"))["cases"]
    if not isinstance(cases, list) or len(cases) < 12:
        raise ValueError("at least 12 semantic cases required")
    identifiers: set[str] = set()
    for case in cases:
        required = {"id", "question", "expected_status", "expected_plan", "expected_rows"}
        if not isinstance(case, dict) or not required.issubset(case):
            raise ValueError("invalid evaluation case")
        if case["id"] in identifiers:
            raise ValueError("duplicate evaluation case id")
        identifiers.add(case["id"])
        if case["expected_status"] not in {"success", "needs_clarification", "unsupported"}:
            raise ValueError("invalid expected status")
        if not isinstance(case["expected_rows"], list):
            raise ValueError("expected rows must be an array")
        if case["expected_status"] == "success" and not isinstance(case["expected_plan"], dict):
            raise ValueError("success must have an explicit standard plan")
        if case["expected_status"] != "success" and (case["expected_rows"] or case["expected_plan"] is not None):
            raise ValueError("non-query case must have empty rows and no validated plan")
        normalize_value(case["expected_rows"])
    return cases


def run_suite(graph: Any, repository: CountingRepository, mode: str, cases: list[dict[str, Any]]) -> dict[str, Any]:
    from app.graph import create_state, to_response

    started = perf_counter()
    results = []
    for case in cases:
        count_before = repository.query_count
        case_started = perf_counter()
        try:
            state = graph.invoke(create_state(case["question"], mode), config={"recursion_limit": 8})
            response = to_response(state).model_dump(mode="json")
            checked = check_case(case, response, repository.query_count - count_before)
            if response.get("model_mode") != mode:
                checked["failures"].append("MODEL_MODE_MISMATCH")
                checked["passed"] = False
                if checked["result_correct"] is not None:
                    checked["result_correct"] = False
        except Exception:
            # Exception text may contain provider or database secrets; never log it.
            checked = {
                "id": case["id"], "expected_status": case["expected_status"],
                "actual_status": "failed", "plan_status_passed": False,
                "result_correct": False if case["expected_status"] == "success" else None,
                "answer_passed": False, "database_query_count": repository.query_count - count_before,
                "passed": False, "failures": ["EVALUATION_INTERNAL_ERROR"],
                "error_code": "EVALUATION_INTERNAL_ERROR", "error_category": "internal",
                "actual_plan": None, "actual_data": [],
            }
        checked["elapsed_ms"] = round((perf_counter() - case_started) * 1000, 3)
        results.append(checked)
    error_counts: Counter[str] = Counter()
    provider_errors: Counter[str] = Counter()
    for result in results:
        categories = set(result["failures"])
        if result["error_code"]:
            categories.add(result["error_code"])
        error_counts.update(categories)
        if result["error_code"] in {"MODEL_PROVIDER_ERROR", "MODEL_TIMEOUT", "MODEL_OUTPUT_INVALID"}:
            provider_errors[result["error_category"] or result["error_code"]] += 1
    return {
        "model_mode": mode,
        "database": "mysql",
        "data_notice": "所有业务数据均为固定模拟数据；mock 仅替代模型，不替代 MySQL。",
        "metric_notice": "仅衡量固定语义用例，不代表通用自然语言查询准确率；澄清/拒绝不计入查询结果正确数。",
        "total_cases": len(cases),
        "plan_status_passed": sum(result["plan_status_passed"] for result in results),
        "query_result_cases": sum(case["expected_status"] == "success" for case in cases),
        "query_results_correct": sum(result["result_correct"] is True for result in results),
        "non_query_cases": sum(case["expected_status"] != "success" for case in cases),
        "non_query_passed": sum(result["passed"] and result["result_correct"] is None for result in results),
        "answers_passed": sum(result["answer_passed"] for result in results),
        "all_checks_passed": sum(result["passed"] for result in results),
        "not_run_cases": 0,
        "error_classification": dict(error_counts),
        "provider_error_classification": dict(provider_errors),
        "elapsed_ms": round((perf_counter() - started) * 1000, 3),
        "cases": results,
        "exit_status": 0 if all(result["passed"] for result in results) else 1,
    }


def emit_report(report: dict[str, Any], output: Path | None) -> None:
    serialized = json.dumps(report, ensure_ascii=False, indent=2)
    if output:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(serialized + "\n", encoding="utf-8")
    print(serialized)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", required=True, choices=("mock", "live"))
    parser.add_argument("--cases", type=Path, default=ROOT / "evals" / "cases.json")
    parser.add_argument("--output", type=Path, help="Optional safe JSON report file")
    args = parser.parse_args(argv)
    started = perf_counter()
    adapter = None
    cases: list[dict[str, Any]] = []
    stage = "configuration"
    try:
        from app.config import load_settings
        from app.graph import build_graph
        from app.model_adapter import create_adapter
        from app.repository import Repository

        cases = load_cases(args.cases)
        settings = load_settings(model_mode=args.mode)
        adapter = create_adapter(settings)
        stage = "database_preflight"
        repository = CountingRepository(Repository(settings))
        health = repository.health()
        version = health.get("server_version", "")
        if health.get("database") != "mysql" or not health.get("database_ready") or not str(version).startswith("8.4."):
            raise ValueError("MySQL 8.4 required")
        graph = build_graph(adapter, repository, settings)
        stage = "evaluation"
        report = run_suite(graph, repository, args.mode, cases)
        report["mysql_version"] = version
        report["python_version"] = sys.version.split()[0]
        report["completed_at_utc"] = datetime.now(UTC).isoformat()
    except Exception as exc:
        code = {"configuration": "EVALUATION_CONFIGURATION_ERROR", "database_preflight": "EVALUATION_DATABASE_UNAVAILABLE"}.get(stage, "EVALUATION_INTERNAL_ERROR")
        safe_cause = getattr(exc, "code", None)
        if safe_cause not in {"DB_UNAVAILABLE", "QUERY_TIMEOUT", "QUERY_FAILED", "INTERNAL_ERROR"}:
            safe_cause = None
        report = {
            "model_mode": args.mode, "database": "mysql", "stage": stage,
            "error_code": code, "cause_code": safe_cause,
            "message": (
                "配置校验未通过；live 必须配置 MODEL_BASE_URL、MODEL_NAME、MODEL_API_KEY。不会回退到 mock。"
                if stage == "configuration" else
                "评测未完成；请检查真实 MySQL 8.4 的可用性及专用只读账号授权。"
            ),
            "total_cases": len(cases), "plan_status_passed": 0,
            "query_result_cases": sum(case["expected_status"] == "success" for case in cases),
            "query_results_correct": 0,
            "non_query_cases": sum(case["expected_status"] != "success" for case in cases),
            "non_query_passed": 0, "answers_passed": 0, "all_checks_passed": 0,
            "not_run_cases": len(cases), "error_classification": {code: 1},
            "provider_error_classification": {}, "cases": [], "mysql_version": None,
            "python_version": sys.version.split()[0],
            "completed_at_utc": datetime.now(UTC).isoformat(),
            "elapsed_ms": round((perf_counter() - started) * 1000, 3), "exit_status": 2,
        }
    finally:
        if adapter is not None and callable(getattr(adapter, "close", None)):
            adapter.close()
    emit_report(report, args.output)
    return int(report["exit_status"])


if __name__ == "__main__":
    raise SystemExit(main())
